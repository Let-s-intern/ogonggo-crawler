  FROM _field_map f
  JOIN job_taxonomy op ON op.parent_id IS NULL AND op.name = f.old_field
  JOIN job_taxonomy np ON np.parent_id IS NULL AND np.name = f.new_field
 WHERE job_taxonomy.parent_id = op.id;

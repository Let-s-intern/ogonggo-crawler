 WHERE job_field_overrides.field_name = 'job_role' AND job_field_overrides.value = r.old_role;

UPDATE job_field_suggestions
   SET value = f.new_field
  FROM _field_map f
 WHERE job_field_suggestions.field_name = 'job_field' AND job_field_suggestions.value = f.old_field;
UPDATE job_field_suggestions
   SET value = r.new_role
  FROM _role_map r
 WHERE job_field_suggestions.field_name = 'job_role' AND job_field_suggestions.value = r.old_role;

-- 분류표. 이름이 바뀌거나 옮기는 직무, 지운 직무를 먼저 옮긴다. 옮길 자리의 이름은 옛 표에 없다

UPDATE job_taxonomy
   SET parent_id = np.id, name = r.new_role, updated_at = datetime('now')
  FROM _role_map r
  JOIN job_taxonomy op ON op.parent_id IS NULL AND op.name = r.old_field
  JOIN job_taxonomy np ON np.parent_id IS NULL AND np.name = r.new_field
 WHERE r.kind <> 'merge' AND job_taxonomy.parent_id = op.id AND job_taxonomy.name = r.old_role;

-- 묶은 직무 중 옛 표에 없는 것(`프론트 풀스택` 등)을 더한다
INSERT INTO job_taxonomy (parent_id, name, sort_order)
SELECT p.id, t.role, t.sort_order
  FROM _target t
  JOIN job_taxonomy p ON p.parent_id IS NULL AND p.name = t.field
 WHERE NOT EXISTS (SELECT 1 FROM job_taxonomy x WHERE x.parent_id = p.id AND x.name = t.role);

DELETE FROM job_taxonomy
 WHERE id IN (SELECT m.id
                FROM job_taxonomy m
                JOIN job_taxonomy p ON p.id = m.parent_id
                JOIN _role_map r ON r.kind = 'merge' AND r.old_field = p.name AND r.old_role = m.name);

-- 합쳐진 직군에 남은 직무(운영자가 넣은 것)는 합친 직군으로 옮기고 빈 직군 행을 지운다
UPDATE job_taxonomy
